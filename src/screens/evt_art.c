ArtId evt_art(u8 evt)
{
    // Entrée absente (0 = ART_TITLE) ou hors table : vignette générique.
    if (evt >= EVT_COUNT || evt_art_table[evt] < ART_FIRST_EVENT)
        return ART_EVT_SCANDALE;
    return (ArtId)evt_art_table[evt];
}

void art_reset(void)
{
    ui_clear();
    ui_art_close();
}
